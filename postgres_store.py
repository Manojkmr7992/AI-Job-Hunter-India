"""Optional PostgreSQL persistence; default remains SQLite."""
import os
from functools import lru_cache
from sqlalchemy import create_engine, text
from dotenv import load_dotenv
from pathlib import Path

load_dotenv(Path(__file__).resolve().parent / '.env')


def postgres_enabled():
    return os.getenv('JOB_HUNTER_DB', 'sqlite').lower() == 'postgres'


@lru_cache(maxsize=1)
def engine():
    url = os.getenv('DATABASE_URL', '')
    if not url:
        raise RuntimeError('DATABASE_URL is required when JOB_HUNTER_DB=postgres')
    if not url.startswith('postgresql+psycopg://'):
        raise RuntimeError('DATABASE_URL must use postgresql+psycopg://')
    return create_engine(url, pool_pre_ping=True)


def pg_init_db():
    with engine().begin() as conn:
        conn.execute(text("""CREATE TABLE IF NOT EXISTS jobs (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            url TEXT NOT NULL UNIQUE,
            title TEXT NOT NULL,
            company TEXT NOT NULL,
            location TEXT NOT NULL,
            country TEXT NOT NULL,
            work_mode TEXT NOT NULL,
            status TEXT NOT NULL DEFAULT 'discovered'
        )"""))


def pg_add_job(job):
    fields = ('url', 'title', 'company', 'location', 'country', 'work_mode')
    params = {k: job[k].strip() for k in fields}
    with engine().begin() as conn:
        conn.execute(text("""INSERT INTO jobs(url,title,company,location,country,work_mode)
            VALUES (:url,:title,:company,:location,:country,:work_mode)
            ON CONFLICT(url) DO UPDATE SET title=excluded.title,
            company=excluded.company, location=excluded.location,
            country=excluded.country, work_mode=excluded.work_mode"""), params)


def pg_list_jobs():
    with engine().connect() as conn:
        return [dict(r) for r in conn.execute(text('SELECT * FROM jobs ORDER BY id DESC')).mappings()]


def pg_update_status(job_id, status):
    with engine().begin() as conn:
        result = conn.execute(text('UPDATE jobs SET status=:status WHERE id=:id'), {'status':status,'id':job_id})
        if result.rowcount == 0:
            raise ValueError('Job not found')
